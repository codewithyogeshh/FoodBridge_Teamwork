/// Direct Supabase REST & WebSocket Realtime Client with resilient offline/online synchronization
class SupabaseService {
  final http.Client _client;
  final String _baseUrl;
  final String _anonKey;
  late final supa.SupabaseClient _supabaseClient;

  // Real-time notification, donation & NGO event stream controllers
  final StreamController<NotificationModel> _notificationStreamController =
      StreamController<NotificationModel>.broadcast();
  final StreamController<DonationModel> _donationStreamController =
      StreamController<DonationModel>.broadcast();
  final StreamController<NGOModel> _ngoStreamController =
      StreamController<NGOModel>.broadcast();
  supa.RealtimeChannel? _realtimeChannel;

  // In-memory fallback caches to ensure ultra-fast responsive UI & offline support
  final List<DonationModel> _localDonations = [];
  final List<NGOModel> _localNGOs = [];
  final List<NotificationModel> _localNotifications = [];
  bool _initializedSeed = false;

  SupabaseService({
    http.Client? client,
    bool enableRealtime = true,
    supa.SupabaseClient? supabaseClient,
  }) : _client = client ?? http.Client(),
       _baseUrl = AppConstants.supabaseUrl,
       _anonKey = AppConstants.supabaseAnonKey {
    try {
      _supabaseClient =
          supabaseClient ??
          supa.SupabaseClient(
            _baseUrl,
            _anonKey,
            authOptions: const supa.AuthClientOptions(autoRefreshToken: false),
          );
      if (enableRealtime) {
        _setupRealtimeChannel();
      }
    } catch (e) {
      debugPrint('SupabaseClient initialization notice: $e');
    }
  }

  Stream<NotificationModel> get notificationStream =>
      _notificationStreamController.stream;

  Stream<DonationModel> get donationStream => _donationStreamController.stream;

  Stream<NGOModel> get ngoStream => _ngoStreamController.stream;

  Map<String, String> get _headers => {
    'apikey': _anonKey,
    'Authorization': 'Bearer $_anonKey',
    'Content-Type': 'application/json',
    'Prefer': 'return=representation',
  };

  void _setupRealtimeChannel() {
    try {
      _realtimeChannel = _supabaseClient.channel('foodbridge_realtime_feed');

      // 1. Listen for new notifications generated by PostgreSQL Triggers
      _realtimeChannel!.onPostgresChanges(
        event: supa.PostgresChangeEvent.insert,
        schema: 'public',
        table: 'notifications',
        callback: (payload) {
          try {
            final record = payload.newRecord;
            if (record.isNotEmpty) {
              final notif = NotificationModel.fromJson(record);
              if (!_localNotifications.any((n) => n.id == notif.id)) {
                _localNotifications.insert(0, notif);
                _notificationStreamController.add(notif);
              }
            }
          } catch (e) {
            debugPrint('Error parsing realtime notification: $e');
          }
        },
      );

      // 2. Listen for real-time donation updates (insert, update, delete)
      _realtimeChannel!.onPostgresChanges(
        event: supa.PostgresChangeEvent.all,
        schema: 'public',
        table: 'donations',
        callback: (payload) {
          try {
            final record = payload.newRecord;
            if (record.isNotEmpty) {
              final donation = DonationModel.fromJson(record);
              _updateLocalDonationFromRealtime(donation);
              _donationStreamController.add(donation);
            }
          } catch (e) {
            debugPrint('Error parsing realtime donation: $e');
          }
        },
      );

      // 3. Listen for real-time NGO changes (new registrations, verification status updates)
      _realtimeChannel!.onPostgresChanges(
        event: supa.PostgresChangeEvent.all,
        schema: 'public',
        table: 'ngos',
        callback: (payload) {
          try {
            final record = payload.newRecord;
            if (record.isNotEmpty) {
              final ngo = NGOModel.fromJson(record);
              _updateLocalNGOFromRealtime(ngo);
              _ngoStreamController.add(ngo);
            }
          } catch (e) {
            debugPrint('Error parsing realtime NGO: $e');
          }
        },
      );

      // 4. Listen for real-time reservation changes (claims, allocations)
      _realtimeChannel!.onPostgresChanges(
        event: supa.PostgresChangeEvent.all,
        schema: 'public',
        table: 'reservations',
        callback: (payload) {
          try {
            final record = payload.newRecord;
            final donId = record['donation_id'] as String?;
            if (donId != null) {
              _updateLocalStatus(donId, DonationStatus.reserved);
            }
          } catch (e) {
            debugPrint('Error parsing realtime reservation: $e');
          }
        },
      );

      // 5. Listen for direct broadcast alerts (NGO, Admin, Donor, Community)
      _realtimeChannel!.onBroadcast(
        event: 'realtime_alert',
        callback: (payload) {
          try {
            final data =
                (payload['payload'] as Map<String, dynamic>?) ?? payload;
            if (data.containsKey('title')) {
              final notif = NotificationModel.fromJson(data);
              if (!_localNotifications.any((n) => n.id == notif.id)) {
                _localNotifications.insert(0, notif);
                _notificationStreamController.add(notif);
              }
            }
          } catch (e) {
            debugPrint('Error parsing broadcast alert: $e');
          }
        },
      );

      // 6. Listen for direct broadcast new_donation events
      _realtimeChannel!.onBroadcast(
        event: 'new_donation',
        callback: (payload) {
          try {
            final data =
                (payload['payload'] as Map<String, dynamic>?) ?? payload;
            if (data.containsKey('title')) {
              final donation = DonationModel.fromJson(data);
              _updateLocalDonationFromRealtime(donation);
              _donationStreamController.add(donation);
            }
          } catch (e) {
            debugPrint('Error parsing broadcast new_donation: $e');
          }
        },
      );

      _realtimeChannel!.subscribe((status, [error]) {
        if (status == supa.RealtimeSubscribeStatus.subscribed) {
          debugPrint('🟢 Supabase Realtime connected and active!');
        } else if (error != null) {
          debugPrint(
            '🟡 Supabase Realtime subscription status: $status ($error)',
          );
        }
      });
    } catch (e) {
      debugPrint('Realtime channel setup error: $e');
    }
  }

  void _updateLocalDonationFromRealtime(DonationModel donation) {
    final idx = _localDonations.indexWhere((d) => d.id == donation.id);
    if (idx != -1) {
      _localDonations[idx] = donation;
    } else {
      _localDonations.insert(0, donation);
    }
  }

  void _updateLocalNGOFromRealtime(NGOModel ngo) {
    final idx = _localNGOs.indexWhere(
      (n) => n.id == ngo.id || n.phone == ngo.phone,
    );
    if (idx != -1) {
      _localNGOs[idx] = ngo;
    } else {
      _localNGOs.insert(0, ngo);
    }
  }

  /// Sync user profile to Supabase on entry/register
  Future<UserProfileModel> syncUserProfile(UserProfileModel profile) async {
    try {
      final payload = {
        'phone': profile.phone,
        'full_name': profile.fullName,
        'role': profile.role.name.toLowerCase(),
        'organization_name': profile.organizationName,
        'avatar_url': profile.avatarUrl,
      };

      final response = await _client
          .post(
            Uri.parse('$_baseUrl/rest/v1/profiles?on_conflict=phone'),
            headers: {
              ..._headers,
              'Prefer': 'resolution=merge-duplicates,return=representation',
            },
            body: jsonEncode(payload),
          )
          .timeout(const Duration(seconds: 4));

      if (response.statusCode == 200 || response.statusCode == 201) {
        final List<dynamic> data = jsonDecode(response.body);
        if (data.isNotEmpty) {
          return UserProfileModel.fromJson(data.first);
        }
      }
    } catch (e) {
      debugPrint('Supabase syncUserProfile notice: $e');
    }
    return profile;
  }

  /// Fetch user profile by registered phone number
  Future<UserProfileModel?> getProfileByPhone(String phone) async {
    try {
      final response = await _client
          .get(
            Uri.parse(
              '$_baseUrl/rest/v1/profiles?phone=eq.${Uri.encodeComponent(phone)}&limit=1',
            ),
            headers: _headers,
          )
          .timeout(const Duration(seconds: 4));

      if (response.statusCode == 200) {
        final List<dynamic> data = jsonDecode(response.body);
        if (data.isNotEmpty) {
          return UserProfileModel.fromJson(data.first);
        }
      }
    } catch (e) {
      debugPrint('Supabase getProfileByPhone notice: $e');
    }
    return null;
  }

  void _initLocalSeed() {
    if (_initializedSeed) return;
    _initializedSeed = true;

    _localNGOs.addAll(SeedData.initialNGOs);
    _localDonations.addAll(SeedData.initialDonations);
    _localNotifications.addAll(SeedData.initialNotifications);
  }

  /// Fetch all notifications from Supabase
  Future<List<NotificationModel>> getNotifications({String? role}) async {
    _initLocalSeed();
    try {
      String endpoint =
          '$_baseUrl/rest/v1/notifications?select=*&order=created_at.desc';
      if (role != null && role.isNotEmpty) {
        endpoint += '&or=(recipient_role.eq.$role,recipient_role.eq.all)';
      }

      final response = await _client
          .get(Uri.parse(endpoint), headers: _headers)
          .timeout(const Duration(seconds: 4));

      if (response.statusCode == 200) {
        final List<dynamic> data = jsonDecode(response.body);
        final results = data
            .map((item) => NotificationModel.fromJson(item))
            .toList();
        if (results.isNotEmpty) {
          // Merge with local cache
          for (final n in results) {
            if (!_localNotifications.any((x) => x.id == n.id)) {
              _localNotifications.add(n);
            }
          }
          if (role != null && role.isNotEmpty) {
            return _localNotifications
                .where(
                  (n) => n.recipientRole == role || n.recipientRole == 'all',
                )
                .toList();
          }
          return List.from(_localNotifications);
        }
      }
    } catch (e) {
      debugPrint('Supabase getNotifications notice: $e');
    }

    if (role != null && role.isNotEmpty) {
      return _localNotifications
          .where((n) => n.recipientRole == role || n.recipientRole == 'all')
          .toList();
    }
    return List.from(_localNotifications);
  }

  /// Mark notification as read
  Future<bool> markNotificationAsRead(String id) async {
    try {
      await _client
          .patch(
            Uri.parse('$_baseUrl/rest/v1/notifications?id=eq.$id'),
            headers: _headers,
            body: jsonEncode({'is_read': true}),
          )
          .timeout(const Duration(seconds: 3));
    } catch (e) {
      debugPrint('Supabase markNotificationAsRead notice: $e');
    }

    final idx = _localNotifications.indexWhere((n) => n.id == id);
    if (idx != -1) {
      _localNotifications[idx] = _localNotifications[idx].copyWith(
        isRead: true,
      );
    }
    return true;
  }

  /// Mark all notifications as read
  Future<bool> markAllNotificationsAsRead(String role) async {
    try {
      await _client
          .patch(
            Uri.parse(
              '$_baseUrl/rest/v1/notifications?recipient_role=eq.$role',
            ),
            headers: _headers,
            body: jsonEncode({'is_read': true}),
          )
          .timeout(const Duration(seconds: 3));
    } catch (e) {
      debugPrint('Supabase markAllNotificationsAsRead notice: $e');
    }

    for (int i = 0; i < _localNotifications.length; i++) {
      if (_localNotifications[i].recipientRole == role ||
          _localNotifications[i].recipientRole == 'all') {
        _localNotifications[i] = _localNotifications[i].copyWith(isRead: true);
      }
    }
    return true;
  }

  /// Fetch all donations from Supabase
  Future<List<DonationModel>> getDonations({String? statusFilter}) async {
    _initLocalSeed();
    try {
      final query = _supabaseClient.from('donations').select();
      final dynamic response;
      if (statusFilter != null && statusFilter.isNotEmpty) {
        response = await query
            .eq('status', statusFilter.toUpperCase())
            .order('created_at', ascending: false)
            .timeout(const Duration(seconds: 10));
      } else {
        response = await query
            .order('created_at', ascending: false)
            .timeout(const Duration(seconds: 10));
      }

      if (response is List && response.isNotEmpty) {
        final results = response
            .map(
              (item) => DonationModel.fromJson(Map<String, dynamic>.from(item)),
            )
            .toList();
        for (final item in results) {
          final idx = _localDonations.indexWhere((d) => d.id == item.id);
          if (idx != -1) {
            _localDonations[idx] = item;
          } else {
            _localDonations.add(item);
          }
        }
      }
    } catch (e) {
      debugPrint('Supabase getDonations SDK notice (using REST fallback): $e');
      try {
        String endpoint =
            '$_baseUrl/rest/v1/donations?select=*&order=created_at.desc';
        if (statusFilter != null && statusFilter.isNotEmpty) {
          endpoint += '&status=eq.${statusFilter.toUpperCase()}';
        }

        final response = await _client
            .get(Uri.parse(endpoint), headers: _headers)
            .timeout(const Duration(seconds: 6));

        if (response.statusCode == 200) {
          final List<dynamic> data = jsonDecode(response.body);
          final results = data
              .map((item) => DonationModel.fromJson(item))
              .toList();
          if (results.isNotEmpty) {
            for (final item in results) {
              final idx = _localDonations.indexWhere((d) => d.id == item.id);
              if (idx != -1) {
                _localDonations[idx] = item;
              } else {
                _localDonations.add(item);
              }
            }
          }
        }
      } catch (err) {
        debugPrint('Supabase getDonations REST notice: $err');
      }
    }

    if (statusFilter != null && statusFilter.isNotEmpty) {
      return _localDonations
          .where((d) => d.status.dbValue == statusFilter.toUpperCase())
          .toList();
    }
    return List.from(_localDonations);
  }

  /// Create a new food donation and instantly notify NGOs & ADMIN via Realtime
  Future<DonationModel> createDonation(DonationModel donation) async {
    _initLocalSeed();
    DonationModel finalCreated = donation;

    try {
      final payload = donation.toJson();
      final isUuid = RegExp(
        r'^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$',
      ).hasMatch(donation.id);
      if (isUuid) {
        payload['id'] = donation.id;
      }

      final res = await _supabaseClient
          .from('donations')
          .insert(payload)
          .select()
          .single()
          .timeout(const Duration(seconds: 15));
      finalCreated = DonationModel.fromJson(Map<String, dynamic>.from(res));
      debugPrint(
        '🟢 Successfully inserted donation in Supabase: ${finalCreated.id}',
      );
    } catch (e) {
      debugPrint('Supabase createDonation SDK notice (trying REST): $e');
      try {
        final payload = donation.toJson();
        final isUuid = RegExp(
          r'^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$',
        ).hasMatch(donation.id);
        if (isUuid) {
          payload['id'] = donation.id;
        }

        final response = await _client
            .post(
              Uri.parse('$_baseUrl/rest/v1/donations'),
              headers: _headers,
              body: jsonEncode(payload),
            )
            .timeout(const Duration(seconds: 10));

        if (response.statusCode == 201 || response.statusCode == 200) {
          final List<dynamic> data = jsonDecode(response.body);
          if (data.isNotEmpty) {
            finalCreated = DonationModel.fromJson(data.first);
            debugPrint(
              '🟢 REST fallback inserted donation: ${finalCreated.id}',
