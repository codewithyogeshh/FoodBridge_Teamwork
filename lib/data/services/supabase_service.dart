      if (response.statusCode == 200) {
        final List<dynamic> data = jsonDecode(response.body);
        if (data.isNotEmpty) {
          return UserProfileModel.fromJson(data.first);
        }
      }
    } catch (e) {
      debugPrint('Supabase getProfileByPhone notice: $e');
    }
    return null;
  }

