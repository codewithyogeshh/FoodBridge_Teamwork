  /// Verify Pickup OTP via PostgreSQL Stored Procedure
  Future<Map<String, dynamic>> verifyPickupOtp({
    required String donationId,
    required String enteredOtp,
    required String ngoId,
  }) async {
    _initLocalSeed();
    try {
      final response = await _client
          .post(
            Uri.parse('$_baseUrl/rest/v1/rpc/verify_pickup_otp'),
            headers: _headers,
            body: jsonEncode({
              'p_donation_id': donationId,
              'p_entered_otp': enteredOtp,
              'p_ngo_id': ngoId,
            }),
          )
          .timeout(const Duration(seconds: 5));

      if (response.statusCode == 200) {
        final Map<String, dynamic> result = jsonDecode(response.body);
        if (result['success'] == true) {
          _updateLocalStatus(donationId, DonationStatus.pickupVerified);
          _broadcastPickupVerifiedAlert(donationId);
        }
        return result;
      }
    } catch (e) {
      debugPrint('Supabase verifyPickupOtp RPC notice: $e');
    }

    // Local OTP verification
    final index = _localDonations.indexWhere((d) => d.id == donationId);
    if (index != -1) {
      final d = _localDonations[index];
      if (d.pickupOtp.trim() == enteredOtp.trim()) {
        _localDonations[index] = d.copyWith(
          status: DonationStatus.pickupVerified,
        );
        _broadcastPickupVerifiedAlert(donationId);
        return {'success': true, 'message': 'Pickup verified successfully'};
      } else {
        return {
          'success': false,
          'message': 'Invalid OTP code. Expected ${d.pickupOtp}',
        };
      }
    }
    return {'success': false, 'message': 'Donation record not found'};
  }

