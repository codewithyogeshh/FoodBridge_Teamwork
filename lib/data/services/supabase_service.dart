  /// Upload photo or document to Supabase Storage bucket
  Future<String?> uploadImage({
    required Uint8List bytes,
    required String filename,
    String bucket = 'donation-images',
  }) async {
    try {
      final cleanName = filename.replaceAll(RegExp(r'[^a-zA-Z0-9._-]'), '_');
      final path = '${DateTime.now().millisecondsSinceEpoch}_$cleanName';
      final isPng = filename.toLowerCase().endsWith('.png');
      final isPdf = filename.toLowerCase().endsWith('.pdf');
      final contentType = isPng
          ? 'image/png'
          : isPdf
              ? 'application/pdf'
              : 'image/jpeg';

      await _supabaseClient.storage.from(bucket).uploadBinary(
        path,
        bytes,
        fileOptions: supa.FileOptions(contentType: contentType, upsert: true),
      );
      final publicUrl = _supabaseClient.storage.from(bucket).getPublicUrl(path);
      debugPrint('🟢 Uploaded $filename to bucket "$bucket": $publicUrl');
      return publicUrl;
    } catch (e) {
      debugPrint('Supabase uploadImage notice (trying REST): $e');
      try {
        final cleanName = filename.replaceAll(RegExp(r'[^a-zA-Z0-9._-]'), '_');
        final path = '${DateTime.now().millisecondsSinceEpoch}_$cleanName';
        final isPng = filename.toLowerCase().endsWith('.png');
        final isPdf = filename.toLowerCase().endsWith('.pdf');
        final contentType = isPng
            ? 'image/png'
            : isPdf
                ? 'application/pdf'
                : 'image/jpeg';

        final res = await _client.post(
          Uri.parse('$_baseUrl/storage/v1/object/$bucket/$path'),
          headers: {
            ..._headers,
            'Content-Type': contentType,
          },
          body: bytes,
        );
        if (res.statusCode == 200 || res.statusCode == 201) {
          final publicUrl = '$_baseUrl/storage/v1/object/public/$bucket/$path';
          debugPrint('🟢 Uploaded $filename via REST: $publicUrl');
          return publicUrl;
        }
      } catch (err) {
        debugPrint('Supabase uploadImage REST error: $err');
      }
      return null;
    }
  }

  /// Fetch all NGOs
  Future<List<NGOModel>> getNGOs({String? verificationStatus}) async {
    _initLocalSeed();
    try {
      final query = _supabaseClient.from('ngos').select();
      final dynamic response;
      if (verificationStatus != null && verificationStatus.isNotEmpty) {
        response = await query
            .eq('verification_status', verificationStatus.toUpperCase())
            .order('created_at', ascending: false)
            .timeout(const Duration(seconds: 10));
      } else {
        response = await query
            .order('created_at', ascending: false)
            .timeout(const Duration(seconds: 10));
      }

      if (response is List && response.isNotEmpty) {
        final results = response
            .map((item) => NGOModel.fromJson(Map<String, dynamic>.from(item)))
            .toList();
        for (final item in results) {
          _updateLocalNGOFromRealtime(item);
        }
      }
    } catch (e) {
      debugPrint('Supabase getNGOs SDK notice (using REST fallback): $e');
      try {
        String endpoint = '$_baseUrl/rest/v1/ngos?select=*&order=created_at.desc';
        if (verificationStatus != null && verificationStatus.isNotEmpty) {
          endpoint += '&verification_status=eq.${verificationStatus.toUpperCase()}';
        }

        final response = await _client
            .get(Uri.parse(endpoint), headers: _headers)
            .timeout(const Duration(seconds: 6));

        if (response.statusCode == 200) {
          final List<dynamic> data = jsonDecode(response.body);
          final results = data.map((item) => NGOModel.fromJson(item)).toList();
          for (final item in results) {
            _updateLocalNGOFromRealtime(item);
          }
        }
      } catch (err) {
        debugPrint('Supabase getNGOs REST notice: $err');
      }
    }

    if (verificationStatus != null && verificationStatus.isNotEmpty) {
      return _localNGOs
          .where((n) =>
              n.verificationStatus.dbValue == verificationStatus.toUpperCase())
          .toList();
    }
    return List.from(_localNGOs);
  }

  /// Register new NGO
  Future<NGOModel> registerNGO(NGOModel ngo) async {
    _initLocalSeed();
    NGOModel finalCreated = ngo;
    try {
      final payload = ngo.toJson();
      final isUuid = RegExp(r'^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$')
          .hasMatch(ngo.id);
      if (isUuid) {
        payload['id'] = ngo.id;
      }

      final res = await _supabaseClient
          .from('ngos')
          .insert(payload)
          .select()
          .single()
          .timeout(const Duration(seconds: 15));
      finalCreated = NGOModel.fromJson(Map<String, dynamic>.from(res));
      debugPrint('🟢 Successfully registered NGO in Supabase: ${finalCreated.id}');
    } catch (e) {
      debugPrint('Supabase registerNGO SDK notice (trying REST): $e');
      try {
        final payload = ngo.toJson();
        final isUuid = RegExp(r'^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$')
            .hasMatch(ngo.id);
        if (isUuid) {
          payload['id'] = ngo.id;
        }

        final response = await _client
            .post(
              Uri.parse('$_baseUrl/rest/v1/ngos'),
              headers: _headers,
              body: jsonEncode(payload),
            )
            .timeout(const Duration(seconds: 10));

        if (response.statusCode == 201 || response.statusCode == 200) {
          final List<dynamic> data = jsonDecode(response.body);
          if (data.isNotEmpty) {
            finalCreated = NGOModel.fromJson(data.first);
            debugPrint('🟢 REST fallback registered NGO: ${finalCreated.id}');
          }
        }
      } catch (err) {
        debugPrint('Supabase registerNGO REST notice: $err');
      }
    }

    _updateLocalNGOFromRealtime(finalCreated);
    _ngoStreamController.add(finalCreated);
    return finalCreated;
  }

  /// Admin update NGO verification status
  Future<bool> updateNGOVerificationStatus(
      String ngoId, NGOVerificationStatus status) async {
    _initLocalSeed();
    try {
      final response = await _client
          .patch(
            Uri.parse('$_baseUrl/rest/v1/ngos?id=eq.$ngoId'),
            headers: _headers,
            body: jsonEncode({'verification_status': status.dbValue}),
          )
          .timeout(const Duration(seconds: 4));

      if (response.statusCode == 200 || response.statusCode == 204) {
        _updateLocalNGOStatus(ngoId, status);
        return true;
      }
    } catch (e) {
      debugPrint('Supabase updateNGOVerificationStatus notice: $e');
    }

    _updateLocalNGOStatus(ngoId, status);
    return true;
  }

  void _updateLocalStatus(String donationId, DonationStatus newStatus) {
    final idx = _localDonations.indexWhere((d) => d.id == donationId);
    if (idx != -1) {
      _localDonations[idx] = _localDonations[idx].copyWith(
        status: newStatus,
        updatedAt: DateTime.now(),
      );
      _donationStreamController.add(_localDonations[idx]);
    }
  }

  void _updateLocalNGOStatus(String ngoId, NGOVerificationStatus status) {
    final idx = _localNGOs.indexWhere((n) => n.id == ngoId);
    if (idx != -1) {
      _localNGOs[idx] = _localNGOs[idx].copyWith(verificationStatus: status);
    }
  }

  void dispose() {
    try {
      _realtimeChannel?.unsubscribe();
      _supabaseClient.dispose();
    } catch (_) {}
    if (!_notificationStreamController.isClosed) {
      _notificationStreamController.close();
    }
    if (!_donationStreamController.isClosed) {
      _donationStreamController.close();
    }
    if (!_ngoStreamController.isClosed) {
      _ngoStreamController.close();
    }
  }
