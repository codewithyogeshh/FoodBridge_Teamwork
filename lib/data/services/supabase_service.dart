    } catch (e) {
      debugPrint('Realtime broadcast error: $e');
    }

    // Attempt persistent insertion into Supabase notifications table
    try {
      Map<String, dynamic> cleanNotif(NotificationModel n) {
        final p = n.toJson();
        final isUuid = RegExp(
          r'^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$',
        ).hasMatch(n.id);
        if (!isUuid) {
          p.remove('id');
        }
        return p;
      }

      await _supabaseClient
          .from('notifications')
          .insert([
            cleanNotif(ngoNotif),
            cleanNotif(adminNotif),
            cleanNotif(donorNotif),
            cleanNotif(volunteerNotif),
            cleanNotif(globalNotif),
          ])
          .timeout(const Duration(seconds: 4));
    } catch (e) {
      debugPrint(
        'Supabase notifications insert notice (table might be local): $e',
      );
    }

    return finalCreated;
  }

  /// Atomic Reservation Lock via PostgreSQL Stored Procedure
  Future<Map<String, dynamic>> reserveDonationAtomic({
    required String donationId,
    required String ngoId,
    required String ngoName,
    bool requiresVolunteerDelivery = false,
    double deliveryFee = 0.0,
  }) async {
    _initLocalSeed();
    try {
      final response = await _client
          .post(
            Uri.parse('$_baseUrl/rest/v1/rpc/reserve_donation_atomic'),
            headers: _headers,
            body: jsonEncode({
              'p_donation_id': donationId,
              'p_ngo_id': ngoId,
              'p_ngo_name': ngoName,
            }),
          )
          .timeout(const Duration(seconds: 5));

      if (response.statusCode == 200) {
        final Map<String, dynamic> result = jsonDecode(response.body);
        if (result['success'] == true) {
          final idx = _localDonations.indexWhere((d) => d.id == donationId);
          if (idx != -1) {
            _localDonations[idx] = _localDonations[idx].copyWith(
              status: DonationStatus.reserved,
              requiresVolunteerDelivery: requiresVolunteerDelivery,
              deliveryFee: deliveryFee,
              reservedNgoId: ngoId,
              reservedNgoName: ngoName,
            );
          }
          _broadcastReservationAlert(
            donationId,
            ngoName,
            requiresVolunteer: requiresVolunteerDelivery,
            deliveryFee: deliveryFee,
          );
          return result;
        }
      }
    } catch (e) {
      debugPrint('Supabase reserveDonationAtomic RPC notice: $e');
    }

    // Local atomic check
    final index = _localDonations.indexWhere((d) => d.id == donationId);
    if (index != -1) {
      if (_localDonations[index].status == DonationStatus.available) {
        _localDonations[index] = _localDonations[index].copyWith(
          status: DonationStatus.reserved,
          requiresVolunteerDelivery: requiresVolunteerDelivery,
          deliveryFee: deliveryFee,
          reservedNgoId: ngoId,
          reservedNgoName: ngoName,
        );
        _broadcastReservationAlert(
          donationId,
          ngoName,
          requiresVolunteer: requiresVolunteerDelivery,
          deliveryFee: deliveryFee,
        );
        return {
          'success': true,
          'message': 'Reserved successfully (Local atomic state locked)',
          'reservation_id':
              'local-res-${DateTime.now().millisecondsSinceEpoch}',
        };
      } else {
        return {
          'success': false,
          'message': 'Donation already reserved or unavailable',
        };
      }
    }
